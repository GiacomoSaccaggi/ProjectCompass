CREATE DATABASE IF NOT EXISTS demo_analytics;

CREATE TABLE demo_analytics.page_views (
    date Date,
    url String,
    country String,
    views UInt32,
    unique_visitors UInt32,
    avg_duration_sec Float32
) ENGINE = MergeTree()
ORDER BY (date, url);

CREATE TABLE demo_analytics.events (
    timestamp DateTime,
    event_type String,
    user_id UInt32,
    page String,
    device String,
    country String
) ENGINE = MergeTree()
ORDER BY (timestamp, event_type);

